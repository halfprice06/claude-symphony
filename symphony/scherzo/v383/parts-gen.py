import re
LAYX = {}  # per-part layout extras, keyed by part number
# c315: MOLA PDF 7: "No more than eight to ten staves per page should be used for any instrument that is subject to multiple ledger lines
#   (i.e. flute, violin, tuba). Up to twelve staves may be used as long as symbols are not crowded." Vln I, Vln II, Vla and Cb had 12 systems on
#   page 2 and 4-8 on page 3; pages 2-3 face each other, so the systems can be shared out with no new page and no new turn (the 1->2 turn stays
#   at 152/153, Cb 140/141). Vc is left at 12: with 10 its turn moves from 152/153 (16 bars' rest after it) to 140/141 (8). Winds keep 12 where
#   the turn needs it (with 10, Fl 1, Fl 2 and Bsn 1 gain a page and Ob 1, Cl 1 turn in shorter rests).
PAPX = {s: r"\paper { max-systems-per-page = 10 }" for s in ("26", "27", "28", "30")}
# c345: Trumpet 2 is a one-page part with no turn; after the tempo words moved into the letters (parts-lib.ily, c345) the page-turn breaker
#   put its last two systems on a second page though page 1 had room. Optimal breaking keeps it to one page, as before.
PAPX["17"] = r"\paper { page-breaking = #ly:optimal-breaking }"
# c345: page turns held where they were before the tempo words moved into the letters (that change re-spaced the lines and the page-turn
#   breaker chose shorter rests: Vln I 204-208 instead of the 60-bar rest 133-192, C.a. 9 bars instead of 24, Hn 3 10 instead of 13,
#   the timpani keep the new 12-bar turn at 225-236: forcing 284 gives them four pages). MOLA PDF 7: "It is preferable for a multi-measure rest to be at the end of a page." Value: last bar of the page.
TURNS = {"05": 288, "14": 288, "26": 152}
def cuelist(cues):
    if not cues: return ""
    return "\\partCues #`(" + " ".join('("%s" "%s" ,%s %d %d)' % tuple(c) for c in cues) + ") "
for suf, name, mid, mus, clef, withx, lay in P:
    clefs = f"\\clef {clef} " if clef else ""
    cl = cuelist(CUES.get(suf[:2]))
    mus = mus.replace("CUES ", cl) if "CUES " in mus else cl + mus
    mt = re.search(r"\\transpose (\S+) (\S+)", mus)
    glob = (r"\transpose %s %s \partGlobal" % mt.groups()) if mt else r"\partGlobal"
    turn = (r"{ \skip 2.*%d \pageTurn }" % TURNS[suf[:2]]) if suf[:2] in TURNS else ""
    w(rf'''\book {{
  \bookOutputSuffix "{suf}"
  \header {{ instrument = "{name}" }}
  {PAPX.get(suf[:2], "")}
  \score {{
    \new Staff = "part" \with {{ \audit "{suf}" midiInstrument = "{mid}" {withx} }}
      << {clefs}{glob} {mus} {turn} >>
    \layout {{ {lay} {LAYX.get(suf[:2], "")} }}
  }}
}}''')
