"""Generate parts.ily: concatenates per-section variables for each instrument.

A missing <section><Instrument> variable becomes full-bar rests of the section's length.
Usage: assemble.py <version-dir>
"""
import sys, os
SECTIONS = [('intro', 14), ('tOne', 18), ('trans', 14), ('tTwo', 22), ('clos', 8),
            ('dev', 46), ('recOne', 12), ('recTwo', 24), ('coda', 18)]
INSTR = ['FluteOne', 'FluteTwo', 'OboeOne', 'OboeTwo', 'CorAnglais', 'ClOne', 'ClTwo', 'BassCl',
         'BsnOne', 'BsnTwo', 'Cbsn', 'HnOne', 'HnTwo', 'HnThree', 'HnFour', 'TptOne', 'TptTwo',
         'TptThree', 'TbnOne', 'TbnTwo', 'BassTbn', 'Tuba', 'Timp', 'Perc', 'HarpR', 'HarpL',
         'VlnOne', 'VlnTwo', 'Vla', 'Vc', 'Cb']
v = sys.argv[1]
# A version may override section lengths with a sections.txt file of 'name bars' lines.
lens = os.path.join(v, 'sections.txt')
if os.path.exists(lens):
    # mvt2: optional third column = quarter beats per bar (default 4), for mixed metre.
    SECTIONS = [(f[0], int(f[1]), int(f[2]) if len(f) > 2 else 4) for f in (l.split() for l in open(lens) if l.strip())]
else:
    SECTIONS = [(a, b, 4) for a, b in SECTIONS]
out = ['\\version "2.24.0"', '% generated by tools/assemble.py — do not edit']
for i in INSTR:
    lo = i[0].lower() + i[1:]
    fn = 'secDrum' if i == 'Perc' else 'sec'
    body = ' '.join(f'\\{fn} "{s}{i}" {n} {q}' for s, n, q in SECTIONS)
    out.append(f'{lo} = {{ {body} }}')
open(os.path.join(v, 'parts.ily'), 'w').write('\n'.join(out) + '\n')
